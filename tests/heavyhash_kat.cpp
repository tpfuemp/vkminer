int failures = 0;

void fail(const char *fmt, ...)
{
    va_list ap;

    std::printf("FAIL: ");
    va_start(ap, fmt);
    std::vprintf(fmt, ap);
    va_end(ap);
    std::printf("\n");
    failures++;
}

void print_bytes(const char *label, const unsigned char *bytes)
{
    std::printf("  %-9s ", label);
    for (int i = 0; i < 32; i++)
        std::printf("%02x", bytes[i]);
    std::printf("\n");
}

