// groestl_kernel.glsl's push block, which x11_kernel.glsl takes over and
// x13_kernel.glsl inherits; keep them in step. Only the top 64 bits of the
// target go; the host re-checks all 256.
struct X13Push {
    uint32_t header[19];  // header words 0..18, little-endian reads of the wire
    uint32_t target[2];   // the top 64 bits, most significant last
    uint32_t nonce_start;
    uint32_t count;
    uint32_t capacity;
};

static_assert(sizeof(X13Push) == 96,
              "groestl_kernel.glsl's push block is 96 bytes");
static_assert(offsetof(X13Push, target) == 76, "push block layout");
static_assert(offsetof(X13Push, nonce_start) == 84, "push block layout");

