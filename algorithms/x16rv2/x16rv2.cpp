// x13's push block, which every stage module declares whether it reads the
// header (the first), the count (all) or the target (the screen).
struct X16Rv2Push {
    uint32_t header[19];  // header words 0..18, little-endian reads of the wire
    uint32_t target[2];   // the top 64 bits, most significant last
    uint32_t nonce_start;
    uint32_t count;
    uint32_t capacity;
};

static_assert(sizeof(X16Rv2Push) == 96,
              "groestl_kernel.glsl's push block is 96 bytes");
static_assert(offsetof(X16Rv2Push, target) == 76, "push block layout");
static_assert(offsetof(X16Rv2Push, nonce_start) == 84, "push block layout");

// A kernel's stages, as KernelSpec::stages indexes them: each stage over the
// 80-byte header, the same over 64 bytes of state, then the screen.
constexpr unsigned kFirstStage = 0;
constexpr unsigned kLaterStage = x16rv2::kStages;
constexpr unsigned kScreen = 2 * x16rv2::kStages;
constexpr unsigned kKernelStages = kScreen + 1;

// Bytes of state each nonce keeps between passes, and the most nonces a
// dispatch holds (64 MiB of state).
constexpr uint64_t kStateBytes = 64;
constexpr uint32_t kMaxBatchNonces = 1u << 20;

