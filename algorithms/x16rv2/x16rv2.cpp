class X16Rv2 final : public Algorithm {
public:
    const char *name() const override { return "x16rv2"; }

    // As in yiimp's stratum table (0x100) and ccminer's.
    double target_factor() const override { return 256.; }

    size_t known_answers(const KnownAnswer **out) const override
    {
        *out = kAnswers;
        return sizeof kAnswers / sizeof kAnswers[0];
    }

    // The device kernel screens on the top 64 bits; see X16Rv2Push.
    int screen_bits() const override { return 64; }

    // Two kernels, as for x13: 64-bit lanes and 2x32. The 64-bit one opens
    // where it builds; the tuner races both.
    KernelSpec kernel(const DeviceInfo &device) const override
    {
#ifdef VKMINER_HAVE_SHADERS
        return spec_for(device.int64 ? kWide : kPairs);
#else
        (void)device;
        return spec_for(kPairs);
#endif
    }

    size_t kernels(const DeviceInfo &device, KernelSpec *out,
                   size_t max) const override
    {
        size_t count = 0;
#ifdef VKMINER_HAVE_SHADERS
        if (device.int64 && count < max) {
            const KernelSpec spec = spec_for(kWide);
            if (spec.spirv)
                out[count++] = spec;
        }
#else
        (void)device;
#endif
        if (count < max) {
            const KernelSpec spec = spec_for(kPairs);
            if (spec.spirv)
                out[count++] = spec;
        }
        return count;
    }

    // The program is the order, which the stages run in.
    uint64_t program_key(const uint32_t *header) const override
    {
        return x16rv2::order_of(header);
    }

    // Sixteen hex digits as ccminer prints an order, position 0 first.
    bool set_benchmark_order(const char *order,
                             uint32_t *header) const override
    {
        uint64_t key;
        if (!x16rv2::parse_order(order, &key)) {
            applog(LOG_ERR, "--benchmark-order wants sixteen hex digits, "
                            "not '%s'", order);
            return false;
        }
        x16rv2::set_order(header, key);
        return true;
    }

    // Position 0 over the header, positions 1..15 over the state, the screen.
    size_t stage_sequence(uint64_t key, uint32_t *out,
                          size_t max) const override
    {
        if (max < x16rv2::kStages + 1)
            return 0;
        out[0] = kFirstStage + x16rv2::stage_at(key, 0);
        for (unsigned i = 1; i < x16rv2::kStages; i++)
            out[i] = kLaterStage + x16rv2::stage_at(key, i);
        out[x16rv2::kStages] = kScreen;
        return x16rv2::kStages + 1;
    }

    size_t prepare(const Dispatch &dispatch, void *out,
                   size_t capacity) const override
    {
        if (!dispatch.header || !dispatch.target
            || capacity < sizeof(X16Rv2Push))
            return 0;

        X16Rv2Push push;

        // Back to wire order, read little-endian.
        for (size_t i = 0; i < 19; i++) {
            unsigned char bytes[4];
            be32enc(bytes, dispatch.header[i]);
            push.header[i] = le32dec(bytes);
        }

        push.target[0] = dispatch.target[6];
        push.target[1] = dispatch.target[7];

        // The nonce is one header word; hash() truncates it the same way.
        push.nonce_start = static_cast<uint32_t>(dispatch.nonce_start);
        push.count = dispatch.count;
        push.capacity = dispatch.capacity;

        std::memcpy(out, &push, sizeof push);
        return sizeof push;
    }

    // The scalar reference: sixteen calls in the header's order, a Tiger
    // before three of them.
    void hash(const uint32_t *header, uint64_t nonce,
              uint32_t out[8]) const override
    {
        unsigned char data[80];
        for (size_t i = 0; i < 19; i++)
            be32enc(data + i * 4, header[i]);
        be32enc(data + 19 * 4, static_cast<uint32_t>(nonce));

        const uint64_t order = x16rv2::order_of(header);
        unsigned char in[80], h[64];
        std::memcpy(in, data, sizeof data);
        size_t len = sizeof data;
        for (unsigned i = 0; i < x16rv2::kStages; i++) {
            const unsigned stage = x16rv2::stage_at(order, i);
            if (x16rv2::tiger_first(stage)) {
                unsigned char t[24];
                tiger192_full(t, in, len);
                std::memset(in, 0, 64);
                std::memcpy(in, t, sizeof t);
                len = 64;
            }
            kStageFns[stage](h, in, len);
            std::memcpy(in, h, sizeof h);
            len = sizeof h;
        }
        std::memcpy(out, in, 32);
    }

private:
    enum Module { kWide, kPairs, kModules };

    // One kernel's 33 stage modules. No SPIR-V is not an error: the CPU
    // backend still has the reference.
    KernelSpec spec_for(Module m) const
    {
        static const char *const kVariant[kModules] = { "int64", "2x32" };

        KernelSpec spec;
        spec.name = name();
        spec.algorithm = this;
        spec.variant = kVariant[m];

#ifdef VKMINER_HAVE_SHADERS
        KernelStage *stages = stages_[m];
        if (!stages[0].spirv) {
            for (unsigned i = 0; i < kKernelStages; i++) {
                const ShaderModule *module = load(module_name(m, i));
                if (!module) {
                    stages[0] = KernelStage{};
                    return spec;
                }
                stages[i].spirv = module->words.data();
                stages[i].spirv_words = module->words.size();
            }
            // Whirlpool over 64 bytes hashes four nonces at once, bitsliced.
            stages[kLaterStage + x16rv2::kWhirlpool].nonces_per_invocation = 4;
        }

        spec.stages = stages;
        spec.stage_count = kKernelStages;
        spec.spirv = stages[0].spirv;
        spec.spirv_words = stages[0].spirv_words;
        spec.storage_buffers = 2;  // the candidates, then the states
        spec.push_constant_bytes = sizeof(X16Rv2Push);
        spec.scratch_bytes = kStateBytes;
        spec.max_batch = kMaxBatchNonces;

        // Groestl hashes two nonces at once as bit planes.
        spec.nonces_per_invocation = 2;
#else
        (void)m;
#endif
        return spec;
    }

#ifdef VKMINER_HAVE_SHADERS
    // The module behind stage index i of kernel m, as CMakeLists.txt names
    // the wrappers it writes.
    static std::string module_name(Module m, unsigned i)
    {
        if (i == kScreen)
            return "x16rv2_screen";
        const unsigned stage = i % x16rv2::kStages;
        std::string name = "x16rv2_" + std::to_string(stage)
                         + (i < kLaterStage ? "_80" : "_64");
        const bool wide = stage == x16rv2::kBlake || stage == x16rv2::kBmw
                       || stage == x16rv2::kJh || stage == x16rv2::kSkein
                       || x16rv2::tiger_first(stage);
        if (m == kWide && wide)
            name += "_int64";
        return name;
    }

    // Each module once, whichever kernels share it.
    const ShaderModule *load(const std::string &name) const
    {
        ShaderModule &module = modules_[name];
        if (module.words.empty() && !load_shader(name.c_str(), &module)) {
            modules_.erase(name);
            return nullptr;
        }
        return &module;
    }

    mutable std::map<std::string, ShaderModule> modules_;
    mutable KernelStage stages_[kModules][kKernelStages] = {};
#endif
};

