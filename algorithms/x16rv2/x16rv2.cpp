// x16rv2: sixteen 512-bit hashes over the 80-byte header in an order the
// previous block's hash chooses (x16rv2_order.h), each over the 64 bytes
// before it, cut to 32 bytes at the end. v2's change from x16r is a Tiger-192
// in front of every Keccak, Luffa and SHA-512, its 24-byte digest zero-padded
// to 64 bytes. Bitcoin's header, nonce at word 19.
//
