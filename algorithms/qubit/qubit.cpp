// The push constant block qubit_kernel.glsl declares; keep the two in step.
// Only the top 64 bits of the target go; the host re-checks all 256.
struct QubitPush {
    uint32_t header[19];  // header words 0..18, little-endian reads of the wire
    uint32_t target[2];   // the top 64 bits, most significant last
    uint32_t nonce_start;
    uint32_t count;
    uint32_t capacity;
};

static_assert(sizeof(QubitPush) == 96,
              "qubit_kernel.glsl's push block is 96 bytes");
static_assert(offsetof(QubitPush, target) == 76, "push block layout");
static_assert(offsetof(QubitPush, nonce_start) == 84, "push block layout");

// The uniform block qubit_kernel.glsl declares: luffa512_80_precompute()'s
// 40 words, which read only the nonce-free part of the header.
struct QubitUniform {
    uint32_t v[40];
};

static_assert(sizeof(QubitUniform) == 160,
              "qubit_kernel.glsl's uniform block is 160 bytes");

