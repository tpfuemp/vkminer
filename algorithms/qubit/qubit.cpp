// qubit: Luffa-512, CubeHash-512, SHAvite-512, SIMD-512 and ECHO-512 in turn,
// the first over the 80-byte block header and each later one over the 64-byte
// digest before it, cut to the first 32 bytes.
//
// Bitcoin's header, nonce at word 19. Every stage is a whole hash with its own
// padding; the primitives in shaders/common/ know none of it. Header words go
// to the device in wire order, and the nonce-free part of Luffa is computed
// here once per job (QubitUniform).

